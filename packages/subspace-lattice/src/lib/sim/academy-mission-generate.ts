/**
 * Generate academy video mission replays from real engine play (MCTS / heuristic).
 *
 * Ep09 — Fleet Draft midgame skirmish (MCTS)
 * Ep10 — Infiltrator warp + Target Lock crawl (Heuristic AI)
 * Ep11 — Lockout (winnerReason=no-moves); AI hunt then engine-composed fallback
 *
 * Usage (cwd = packages/subspace-lattice):
 *   bash scripts/academy-mission-generate.sh --write
 */
